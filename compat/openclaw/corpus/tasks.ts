const IMPLEMENT_EDIT: CorpusTask = {
  taskId: "implement-edit",
  title: "Agent loop: implement a scoring function and verify it",
  surface: {
    kind: "agent-exec",
    instruction:
      "Implement the function wordScore(word) in game.js exactly as documented in its docstring, " +
      "then run the command `node verify.js` and confirm it prints GAME-OK.",
  },
  fixture(workdir) {
    writeFileSync(
      join(workdir, "game.js"),
      [
        "/**",
        " * Score a word for a word game.",
        " *",
        " * The score is the sum of letter values: vowels (a, e, i, o, u) are worth",
        " * 1 point each; every other lowercase letter is worth 3 points. Characters",
        " * that are not lowercase letters are worth 0 points.",
        " */",
        "function wordScore(word) {",
        "  // TODO: implement per the docstring above.",
        "  return 0;",
        "}",
        "",
        "module.exports = { wordScore };",
        "",
      ].join("\n"),
    );
    writeFileSync(
      join(workdir, "verify.js"),
      [
        "const { wordScore } = require('./game.js');",
        "const cases = [",
        "  ['a', 1], ['b', 3], ['z', 3], ['aeiou', 5], ['xyz', 9],",
        "  ['', 0], ['A', 0], ['a1', 1], ['hello', 3 + 1 + 3 + 3 + 1],",
        "];",
        "for (const [word, expected] of cases) {",
        "  const got = wordScore(word);",
        "  if (got !== expected) {",
        "    console.error(`FAIL ${JSON.stringify(word)}: expected ${expected}, got ${got}`);",
        "    process.exit(1);",
        "  }",
        "}",
        "console.log('GAME-OK');",
        "",
      ].join("\n"),
    );
  },
  verify(input) {
    if (input.exitCode !== 0) {
      return { resolved: false, checkOutput: `agent exec exited ${input.exitCode}` };
    }
    if (!input.stdout.includes("GAME-OK")) {
      return {
        resolved: false,
        checkOutput: `the run's output does not confirm GAME-OK (stdout tail: ${input.stdout.slice(-300)})`,
      };
    }
    return { resolved: true, checkOutput: "agent run confirmed GAME-OK" };
  },
};

