/** How each task is driven (the app's own CLI surfaces). */
export type TaskSurface =
  | { readonly kind: "agent-exec"; readonly instruction: string }
  | {
      readonly kind: "infer";
      readonly subcommand: readonly string[];
      readonly timeoutMs: number;
    };

export interface CorpusTask {
  readonly taskId: string;
  readonly title: string;
  /** The task's CLI surface (the app's own command). */
  readonly surface: TaskSurface;
  /** Build the fresh workspace fixture. */
  readonly fixture: (workdir: string) => void;
  /**
   * The loopback fixture page this task needs served while it runs
   * (the browser task's token page; absent = no page to serve).
   */
  readonly loopbackPage?: { readonly port: number; readonly token: string };
  /** Mechanically verify the outcome (workspace + run result). */
  readonly verify: (input: {
    readonly workdir: string;
    readonly stdout: string;
    readonly stderr: string;
    readonly exitCode: number;
  }) => { readonly resolved: boolean; readonly checkOutput: string };
}

