const BROWSER_ANSWER: CorpusTask = {
  taskId: "browser-answer",
  title: "Browser: open the loopback page and report the displayed token",
  surface: {
    kind: "agent-exec",
    instruction:
      `Open http://127.0.0.1:8901/token.html with the browser tool, read the access token ` +
      `displayed on the page, and write EXACTLY that token as the only line of answer.txt in the ` +
      `current directory. Do not guess the token; you must read it from the page.`,
  },
  fixture(workdir) {
    writeFileSync(
      join(workdir, "answer.txt"),
      "",
    );
  },
  loopbackPage: { port: 8901, token: BROWSER_TASK_TOKEN },
  verify(input) {
    if (input.exitCode !== 0) {
      return { resolved: false, checkOutput: `agent exec exited ${input.exitCode}` };
    }
    const answer = (() => {
      try {
        return readFileSync(join(input.workdir, "answer.txt"), "utf8").trim();
      } catch {
        return "";
      }
    })();
    if (answer !== BROWSER_TASK_TOKEN) {
      return {
        resolved: false,
        checkOutput: `answer.txt carries ${JSON.stringify(answer.slice(0, 80))} (expected the page token)`,
      };
    }
    return { resolved: true, checkOutput: "answer.txt carries the page's displayed token" };
  },
};

