/**
 * The PPR-023 representative OpenClaw corpus — small, real, mechanically
 * verifiable tasks of the kind OpenClaw exists for, each designed to
 * exercise one declared execution-graph edge through the REAL pinned
 * OpenClaw runtime (the app's own documented CLI surfaces — `openclaw
 * agent exec` one-shot runs for the agent loop; the stable
 * `openclaw infer <capability>` CLI for the specialized media surfaces;
 * every axis the runtime reads comes from the certified --config file,
 * zero code changes):
 *
 *  1. implement-edit      (openclaw.agent-loop.main) — a real code edit
 *     through the agent's exec/read/write tools + a verification command
 *     the agent runs itself (`agent exec` with the coding tool profile
 *     over a fresh --cwd workspace).
 *  2. describe-image      (openclaw.media-understanding.image) — the
 *     deterministic corpus swatch described through the app's own
 *     `infer image describe` capability surface (the image-capable
 *     tools.media path); verification parses the description JSON and
 *     checks the color word.
 *  3. transcribe-memo     (openclaw.media-understanding.audio) — a voice
 *     memo (the corpus's known-phrase fixture, generated by the same
 *     supply's TTS surface at corpus-build time) transcribed through
 *     the app's own `infer audio transcribe` capability surface;
 *     verification checks the known phrase's content words.
 *  4. speak-text          (openclaw.tool.tts-openai) — the app's own
 *     `infer tts convert` capability surface synthesizing a known
 *     sentence to an output path; verification reads the audio artifact
 *     (RIFF/WAV or fmt-appropriate magic + size sanity).
 *  5. generate-image      (openclaw.tool.image-generate-openai) — the
 *     app's own `infer image generate` capability surface producing an
 *     image to an output path; verification reads the artifact (PNG/JPEG
 *     magic + plausible dimensions).
 *  6. browser-answer      (browser surface riding the delegated main
 *     seam) — a loopback page the agent must OPEN with the browser
 *     tool, READ the displayed token, and write it to a file
 *     (browser-use intelligence is the model's — actuation is
 *     app-owned; the task verifies the browser rail actually launched
 *     AND the answer is correct).
 *
 * Every task carries: the fresh-workspace fixture builder (pure
 * filesystem writes), the task's CLI surface + arguments (the app's
 * own surfaces only), and a MECHANICAL verifier (deterministic checks
 * over the workspace + run result — never an LLM judging an LLM).
 *
 * MEDIA QUOTA LAW (binding): the two media-consuming tasks
 * (transcribe-memo's fixture build and speak-text / generate-image)
 * each attempt their supply surface ONCE per battery run; a 429 is
 * recorded as BLOCKED/NOT-RUN with owner "operator-provider boundary
 * (supply media quota)" and NEVER retried.
 */

