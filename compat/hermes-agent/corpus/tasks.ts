/**
 * The PPR-022 representative general-agent corpus — small, real,
 * mechanically verifiable tasks of the kind Hermes-Agent exists for, each
 * designed to exercise one declared execution-graph edge through the
 * REAL pinned Hermes runtime (one-shot `hermes -z` runs — the app's own
 * headless user surface — plus the pinned transcription surface driven
 * through its own module entry):
 *
 *  1. implement-edit      (hermes.agent-loop.main +
 *     hermes.auxiliary.title-generation) — a real code edit through the
 *     agent's write_file/terminal tools + a verification command the
 *     agent runs itself; every fresh session also fires the automatic
 *     title-generation aux call;
 *  2. vision-qa           (hermes.auxiliary.vision-analyze) — the agent
 *     must load a local image with the vision_analyze tool and answer a
 *     question about it (the aux vision path — the custom provider
 *     profile declares no native vision);
 *  3. context-compaction  (hermes.auxiliary.compression +
 *     hermes.agent-loop.main) — a multi-file read+append task run with a
 *     small context_length + compression threshold so the compressor's
 *     own summarization call fires mid-task;
 *  4. speak-text          (hermes.tool.tts-openai) — the agent must
 *     synthesize speech through the text_to_speech tool into an output
 *     path; verification reads the audio artifact (RIFF/WAV header +
 *     duration sanity);
 *  5. transcribe-memo     (hermes.tool.stt-openai) — a voice memo
 *     (the corpus's known-phrase fixture, generated by the same supply's
 *     TTS surface at corpus-build time) transcribed through the pinned
 *     runtime's own transcribe_audio surface;
 *  6. generate-image      (hermes.tool.image-generate-openai) — the
 *     agent must generate an image through the image_generate tool;
 *     verification reads the cached image artifact (PNG/JPEG magic +
 *     plausible dimensions).
 *
 * Every task carries: the fresh-workspace fixture builder (pure
 * filesystem writes), the driver task-spec fragment (instruction,
 * toolsets, runtime config axes), and a MECHANICAL verifier
 * (deterministic checks over the workspace + run result — never an LLM
 * judging an LLM).
 */

