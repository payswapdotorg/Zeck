const TRANSCRIBE_MEMO: CorpusTask = {
  taskId: "transcribe-memo",
  title: "STT: transcribe a voice memo through the pinned runtime's transcription surface",
  spec: {
    instruction: "",
    toolsets: "",
    maxTurns: 1,
  },
  fixture(workdir) {
    copyFileSync(KNOWN_PHRASE_WAV_PATH, join(workdir, "voice-memo.wav"));
  },
  verify({ workdir, stdout }) {
    const line = stdout
      .split("\n")
      .reverse()
      .find((l) => l.startsWith("HERMES_MEDIA:"));
    if (line === undefined) {
      return { resolved: false, checkOutput: "no HERMES_MEDIA result line on stdout" };
    }
    let parsed: { ok?: unknown; transcript?: unknown; provider?: unknown; error?: unknown };
    try {
      parsed = JSON.parse(line.slice("HERMES_MEDIA:".length)) as typeof parsed;
    } catch {
      return { resolved: false, checkOutput: "unparseable HERMES_MEDIA result line" };
    }
    if (parsed.ok !== true) {
      return {
        resolved: false,
        checkOutput: `transcription failed: ${String(parsed.error ?? "unknown").slice(0, 200)}`,
      };
    }
    const transcript = String(parsed.transcript ?? "");
    const lower = transcript.toLowerCase();
    const expected = KNOWN_PHRASE_TEXT.toLowerCase();
    const words = expected.split(/\s+/).filter((word) => /[a-z]/.test(word));
    const hits = words.filter((word) => lower.includes(word)).length;
    const ok = hits >= Math.ceil(words.length * 0.7);
    return {
      resolved: ok,
      checkOutput: ok
        ? `T5 ok (provider=${String(parsed.provider)}: "${transcript.slice(0, 80)}")`
        : `transcript did not match the known phrase (got "${transcript.slice(0, 120)}")`,
    };
  },
};

