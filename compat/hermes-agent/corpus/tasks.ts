const SPEAK_TEXT: CorpusTask = {
  taskId: "speak-text",
  title: "TTS: synthesize a spoken confirmation through the text_to_speech tool",
  spec: {
    instruction:
      "Use the text_to_speech tool to synthesize exactly this text: 'The Hermes proof is " +
      "complete and every surface is delegated.' Save the audio with output_path set to " +
      "'spoken.wav' (a relative path — it lands in the current directory). Your final " +
      "message must confirm the audio file was created.",
    toolsets: "tts",
    maxTurns: 15,
  },
  fixture(workdir) {
    writeFileSync(join(workdir, "task.txt"), "synthesize: The Hermes proof is complete.\n");
  },
  verify({ workdir, home, stdout }) {
    const candidates = [join(workdir, "spoken.wav"), join(home, "voice-memos", "spoken.wav")];
    const path = candidates.find((candidate) => existsSync(candidate));
    if (path === undefined) {
      return {
        resolved: false,
        checkOutput: `no spoken.wav artifact (workspace ${join(workdir, "spoken.wav")} nor ${join(home, "voice-memos", "spoken.wav")}; stdout tail: ${stdout.slice(-160).replace(/\s+/g, " ")})`,
      };
    }
    const data = readFileSync(path);
    if (data.length < 2000) {
      return { resolved: false, checkOutput: `audio artifact too small (${data.length} bytes)` };
    }
    // A RIFF/WAV header check (the supply's default format is wav).
    const isRiff =
      data.length > 44 &&
      data[0] === 0x52 &&
      data[1] === 0x49 &&
      data[2] === 0x46 &&
      data[3] === 0x46;
    if (!isRiff) {
      return {
        resolved: false,
        checkOutput: `audio artifact is not RIFF/WAV (first bytes: ${data.subarray(0, 4).toString("hex")})`,
      };
    }
    return {
      resolved: true,
      checkOutput: `T4 ok (${path.slice(workdir.length > 0 && path.startsWith(workdir) ? workdir.length : 0)} — ${data.length} bytes, RIFF/WAV)`,
    };
  },
};

