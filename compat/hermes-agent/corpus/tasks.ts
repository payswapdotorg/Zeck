const CONTEXT_COMPACTION: CorpusTask = {
  taskId: "context-compaction",
  title: "Compression: multi-file read+append under a small context window",
  spec: {
    instruction:
      "Process the four report files a.txt, b.txt, c.txt and d.txt STRICTLY one at a time, " +
      "in this exact order: (1) read a.txt, then append its FIRST word as a new line to " +
      "notes/words.txt; (2) read b.txt, append its first word; (3) read c.txt, append " +
      "its first word; (4) read d.txt, append its first word — one read and one append per " +
      "file, never batched. After all four are processed, RE-READ notes/words.txt from disk " +
      "and create summary.txt containing exactly the lines you see there, in order (do not " +
      "rely on your memory of earlier turns — the durable file is the source of truth).",
    toolsets: "file",
    // A small-but-legal context window + threshold fires the compressor's
    // own summarization call mid-task (the app's own configuration axes).
    // The pinned runtime ENFORCES a minimum 64,000-token window (live-
    // verified: 16,384 is refused at startup) and its ratio math floors
    // every trigger at ~85% of the effective budget — so the documented
    // compression.threshold_tokens cap pins the trigger low enough that
    // the growing session crosses it mid-task. CAP SIZING (live-measured
    // boundary, instrumented diagnostic + battery runs 2026-09-30): the
    // runtime's rough chars/4 estimate OVERSTATES the real prompt by
    // ~2.5k tokens, and the preflight deferral architecture fires
    // compression only once the provider's REAL usage crosses the cap
    // with a successor call — at cap 15,000 the leanest observed model
    // path kept real usage under the cap until the final call (no
    // successor → the edge never fired, battery run 3); at cap 10,000
    // every re-crossing re-fires the compressor and the live divergence
    // tail drained a whole 30-request supply window into 15s cooldown
    // crawls (task wall-clock timeout, battery run 4). At cap 12,000 the
    // SECOND full fixture read lands real usage at ~15k — over the cap
    // with the read/append/re-read tail still ahead — so the compressor
    // fires 2–3 passes deterministically regardless of read strategy,
    // while staying above the ~7k incompressible system+tools floor (no
    // anti-thrash trip) and inside one supply window (no crawl).
    contextLength: 65_536,
    compressionThreshold: 0.3,
    compressionTokenCap: 12_000,
    maxTurns: 60,
  },
  fixture(workdir) {
    mkdirSync(join(workdir, "notes"), { recursive: true });
    writeFileSync(join(workdir, "notes", "words.txt"), "");
    for (const file of COMPACTION_FILES) {
      writeFileSync(join(workdir, file.name), file.body);
    }
  },
  verify({ workdir }) {
    const summaryPath = join(workdir, "summary.txt");
    if (!existsSync(summaryPath)) {
      return { resolved: false, checkOutput: "summary.txt missing" };
    }
    const content = readFileSync(summaryPath, "utf8");
    const words = content
      .split(/\r?\n/)
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line.length > 0);
    const expected = COMPACTION_FILES.map((file) => file.firstWord);
    const ok = words.length === 4 && expected.every((word, index) => words[index] === word);
    return {
      resolved: ok,
      checkOutput: ok
        ? "T3 ok (summary.txt = alpha/bravo/charlie/delta)"
        : `summary.txt lines: ${JSON.stringify(words)}`,
    };
  },
};

