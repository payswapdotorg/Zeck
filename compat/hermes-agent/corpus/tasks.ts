export interface CorpusTask {
  readonly taskId: string;
  readonly title: string;
  /** The driver task-spec fragment (instruction, toolsets, runtime axes). */
  readonly spec: {
    readonly instruction: string;
    /** The `-t/--toolsets` value for the one-shot run. */
    readonly toolsets: string;
    /** Extra model/runtime config axes for this task's HERMES_HOME config.yaml. */
    readonly contextLength?: number;
    readonly compressionThreshold?: number;
    /** The compression.threshold_tokens absolute cap (fires at the LOWER of ratio vs cap). */
    readonly compressionTokenCap?: number;
    readonly maxTurns?: number;
  };
  /** Build the fresh workspace fixture. */
  readonly fixture: (workdir: string) => void;
  /** Mechanically verify the outcome (workspace + run result). */
  readonly verify: (input: {
    readonly workdir: string;
    readonly home: string;
    readonly stdout: string;
    readonly stderr: string;
    readonly exitCode: number;
  }) => { readonly resolved: boolean; readonly checkOutput: string };
}

