const GENERATE_IMAGE: CorpusTask = {
  taskId: "generate-image",
  title: "Image generation: draw a simple icon through the image_generate tool",
  spec: {
    instruction:
      "Use the image_generate tool to create an image with this prompt: 'a flat minimal " +
      "vector icon of a single teal circle centered on a white background'. Use the square " +
      "aspect ratio. Your final message must confirm the image was generated and report " +
      "the path where it was saved.",
    toolsets: "image_gen",
    maxTurns: 15,
  },
  fixture(workdir) {
    writeFileSync(join(workdir, "task.txt"), "draw: teal circle icon\n");
  },
  verify({ home, stdout }) {
    const imagesDir = join(home, "cache", "images");
    if (!existsSync(imagesDir)) {
      return {
        resolved: false,
        checkOutput: `no image cache directory at ${imagesDir} (stdout tail: ${stdout.slice(-160).replace(/\s+/g, " ")})`,
      };
    }
    const { readdirSync, statSync } = require("node:fs") as typeof import("node:fs");
    const entries = readdirSync(imagesDir)
      .map((name) => join(imagesDir, name))
      .filter((path) => statSync(path).isFile())
      .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);
    const newest = entries[0];
    if (newest === undefined) {
      return { resolved: false, checkOutput: "image cache directory is empty" };
    }
    const data = readFileSync(newest);
    if (data.length < 5000) {
      return { resolved: false, checkOutput: `image artifact too small (${data.length} bytes)` };
    }
    // PNG or JPEG magic (the supply serves JPEG bytes under a .png name —
    // disclosed; the verifier accepts both magics).
    const isPng = data[0] === 0x89 && data[1] === 0x50 && data[2] === 0x4e && data[3] === 0x47;
    const isJpeg = data[0] === 0xff && data[1] === 0xd8 && data[2] === 0xff;
    if (!isPng && !isJpeg) {
      return {
        resolved: false,
        checkOutput: `artifact is neither PNG nor JPEG (first bytes: ${data.subarray(0, 4).toString("hex")})`,
      };
    }
    return {
      resolved: true,
      checkOutput: `T6 ok (${newest} — ${data.length} bytes, ${isPng ? "PNG" : "JPEG"})`,
    };
  },
};

